"""Turn coverage leftovers into a reviewable list of MISSING passages.

Print text that no app field claimed is grouped into passages (same page,
consecutive leftover lines). Each passage is compared with the app fields the
matcher could not place ("not in print"): if one shares most of its letters,
the passage is "heavily changed" (the app has it, reworded) rather than missing.

Writes docs/fidelity/missing-from-app.md.
Run:  python scripts/fidelity/missing.py
"""
import os
import re
from collections import defaultdict

import fidelity as F

OUT = os.path.join(F.ROOT, 'docs', 'fidelity', 'missing-from-app.md')
LABEL = re.compile(r'[\]\[]?\s*(Crucial )?Instant Insight:?')
SK = lambda t: re.sub(r'[^A-Za-zא-ת]', '', t).lower()


def shingles(t, k=6):
    s = SK(t)
    return {s[i:i + k] for i in range(max(0, len(s) - k + 1))}


def main():
    diffs, _ = F.run_all()
    unclaimed = [d for d in diffs if d.kind == 'print-unclaimed' and d.cls == 'missing-from-app']
    unfound = [d for d in diffs if d.kind == 'app-only-field']
    # group leftover lines into passages: same page and flow, adjacent lines
    by_page = defaultdict(list)
    for d in unclaimed:
        by_page[(d.pages[0], d.key)].append(d)
    passages = []
    for (pg, stream), ds in sorted(by_page.items()):
        ds.sort(key=lambda d: d.boxes[0][2])
        cur = [ds[0]]
        for d in ds[1:]:
            if d.boxes[0][2] - cur[-1].boxes[0][4] < 25:
                cur.append(d)
            else:
                passages.append((pg, stream, cur))
                cur = [d]
        passages.append((pg, stream, cur))
    app_sh = [(f, shingles(f.app)) for f in unfound]
    # every app field in the whole app, to tell "not repeated here" from "absent"
    everywhere = {}
    for source, _ in {v[0]: v for v in F.UNITS.values()}.values():
        for f in F.app_fields(source):
            for g in shingles(f.nt.s):
                everywhere.setdefault(g, set()).add(f'{f.file} {f.path}')
    rows_missing, rows_changed, rows_elsewhere, small = [], [], [], 0
    ui_labels, title_pages = 0, []
    for pg, stream, ds in passages:
        text = ' '.join(d.print for d in ds)
        # The app draws these labels itself (the "Insight" button), so the print's
        # label text has no field to match.
        stripped = LABEL.sub(' ', text).strip()
        if not SK(stripped):
            ui_labels += 1
            continue
        text = stripped
        if pg <= 4:
            title_pages.append((pg, text))
            continue
        if len(SK(text)) < 12:
            small += 1
            continue
        sh = shingles(text)
        best, score = None, 0.0
        for f, fs in app_sh:
            if not fs:
                continue
            s = len(sh & fs) / max(1, min(len(sh), len(fs)))
            if s > score:
                best, score = f, s
        row = (pg, pg - 24, stream, text, best, score)
        if score >= 0.5:
            rows_changed.append(row)
            continue
        # how much of the passage exists somewhere in the app?
        hits = [g for g in sh if g in everywhere]
        cover = len(hits) / max(1, len(sh))
        where = ''
        if hits:
            from collections import Counter
            where = Counter(x for g in hits for x in everywhere[g]).most_common(1)[0][0]
        (rows_elsewhere if cover >= 0.8 else rows_missing).append(row + (cover, where))
    lines = ['# Print text missing from the app', '',
             'Generated by `scripts/fidelity/missing.py`. Each passage is print text that no app',
             'field matched. "Heavily changed" passages resemble an app field that is too',
             'different to match automatically; "missing" passages have no counterpart at all.',
             f'Fragments under 12 letters ({small}) are omitted here; they are listed in `findings/`.', '',
             f'"Instant Insight:" labels ({ui_labels}) are drawn by the app itself and are not listed.', '',
             '## Cover, title and copyright pages (PDF 1–4)', '',
             'Not in the app. Whether the app should carry them is a product decision:', '']
    lines += [f'- p{pg}: {t[:160]}' for pg, t in title_pages]
    lines += ['',
             f'## Missing ({len(rows_missing)} passages)', '',
             '| PDF page | Siddur page | Text | ', '|---|---|---|']
    for pg, sp, stream, text, _, _, cover, where in rows_missing:
        lines.append(f'| {pg} | {sp if sp > 0 else "front"} | {text[:220].replace("|", "/")} |')
    lines += ['', f'## Present elsewhere in the app, not repeated here ({len(rows_elsewhere)} passages)', '',
              'The text exists in another place in the app (often replaced here by a link).',
              'Confirm each is intentional.', '',
              '| PDF page | Siddur page | Text | Found in |', '|---|---|---|---|']
    for pg, sp, stream, text, _, _, cover, where in rows_elsewhere:
        lines.append(f'| {pg} | {sp if sp > 0 else "front"} | {text[:140].replace("|", "/")} | `{where}` ({cover:.0%}) |')
    lines += ['', f'## Heavily changed ({len(rows_changed)} passages)', '',
              '| PDF page | Print text | Closest app field |', '|---|---|---|']
    for pg, sp, stream, text, best, score in rows_changed:
        lines.append(f'| {pg} | {text[:140].replace("|", "/")} | `{best.file}` {best.path} ({score:.0%}) |')
    with open(OUT, 'w', encoding='utf-8') as fh:
        fh.write('\n'.join(lines) + '\n')
    print('missing passages:', len(rows_missing), '| elsewhere in app:', len(rows_elsewhere),
          '| heavily changed:', len(rows_changed), '| tiny fragments:', small)


if __name__ == '__main__':
    main()
