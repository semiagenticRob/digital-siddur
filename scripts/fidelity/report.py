"""Write the fidelity report: docs/fidelity/{SUMMARY.md, findings/<unit>.json, ledger.json}.

Every finding gets a disposition in ledger.json, keyed by its fingerprint, so
re-runs keep earlier decisions:
  rav-review        Hebrew difference (letters, nikud, meteg, maqaf, punctuation
                    in Hebrew text) — awaiting the rav
  cantillation      print has Torah trope the app intentionally omits
  english-review    English difference held back from automatic fixing
                    (near Hebrew, markdown/link, weak match, possible print typo)
  intentional       deliberate app adaptation (page references -> links)
  missing-from-app  print text with no app counterpart
  not-in-print      app text with no print counterpart
A human may set any entry to accepted / fix / print-typo; that decision is kept.

Run:  python scripts/fidelity/report.py
"""
import json
import os
import re
from collections import Counter, defaultdict

import fidelity as F

OUT = os.path.join(F.ROOT, 'docs', 'fidelity')
LEDGER = os.path.join(OUT, 'ledger.json')
XREF = re.compile(r'\bpage \d+|\b(above|below) on \d+|\bon \d+\b', re.I)


def disposition(d):
    if d.kind == 'print-unclaimed':
        return 'missing-from-app' if d.cls == 'missing-from-app' else 'print-residue'
    if d.kind == 'app-only-field':
        return 'not-in-print'
    if d.cls == 'he-cantillation':
        return 'cantillation'
    if d.cls.startswith('he-') or d.key in ('heText', 'inlineRubric'):
        return 'rav-review'
    if XREF.search(d.print + ' ' + d.print_context) and re.search(r'\bhere\b|\d', d.app + d.print):
        return 'intentional'
    return 'english-review'


def main():
    diffs, stats = F.run_all()
    old = json.load(open(LEDGER, encoding='utf-8')) if os.path.exists(LEDGER) else {}
    ledger = {}
    by_unit = defaultdict(list)
    for d in diffs:
        auto = disposition(d)
        prev = old.get(d.fingerprint, {})
        human = prev.get('decision') if prev.get('by') == 'human' else None
        ledger[d.fingerprint] = {'unit': d.unit, 'class': d.cls,
                                 'decision': human or auto, 'by': 'human' if human else 'tool'}
        by_unit[d.unit.split('|')[0] or 'coverage'].append({
            'id': d.fingerprint, 'decision': ledger[d.fingerprint]['decision'], 'class': d.cls,
            'kind': d.kind, 'file': d.file, 'path': d.path, 'field': d.key,
            'app': d.app, 'print': d.print, 'app_context': d.app_context,
            'print_context': d.print_context, 'pages': d.pages, 'boxes': d.boxes,
        })
    os.makedirs(os.path.join(OUT, 'findings'), exist_ok=True)
    for unit, items in by_unit.items():
        with open(os.path.join(OUT, 'findings', f'{unit}.json'), 'w', encoding='utf-8') as fh:
            json.dump(items, fh, ensure_ascii=False, indent=1)
            fh.write('\n')
    with open(LEDGER, 'w', encoding='utf-8') as fh:
        json.dump(ledger, fh, ensure_ascii=False, indent=0, sort_keys=True)
        fh.write('\n')

    dec = Counter(v['decision'] for v in ledger.values())
    units = list(F.UNITS)
    lines = ['# Print fidelity report', '',
             'Generated by `scripts/fidelity/report.py`. The print PDF is the authority; see',
             '`scripts/fidelity/README.md` for the method and how to re-run.', '',
             '## Open items by decision', '', '| Decision | Count |', '|---|---|']
    for k, n in dec.most_common():
        lines.append(f'| {k} | {n} |')
    lines += ['', '## By section', '',
              '| Section | App fields | Not found in print | Rav review | English review | Cantillation | Intentional |',
              '|---|---|---|---|---|---|---|']
    for u in units:
        items = by_unit.get(u, [])
        c = Counter(i['decision'] for i in items)
        st = stats.get(u, {})
        lines.append(f"| {u} | {st.get('fields', 0)} | {st.get('fields_unfound', 0)} | {c['rav-review']} | "
                     f"{c['english-review']} | {c['cantillation']} | {c['intentional']} |")
    cov = by_unit.get('coverage', []) + [i for u in units for i in by_unit.get(u, []) if i['kind'] == 'print-unclaimed']
    lines += ['', '## Print text with no app counterpart', '',
              f'{len([i for i in diffs if i.kind == "print-unclaimed"])} line fragments; full list in `findings/*.json` '
              '(kind `print-unclaimed`). Running heads, page numbers and the haskamos images are excluded by design.', '',
              '## Applied corrections', '',
              '- English: `english-fixes.json` (each entry: field, old, new, print page).',
              '- Divine Name per the print (יְהֹוָה): `divine-name-fixes.json`.',
              '- English items held for a human: `english-held.json`.', '']
    with open(os.path.join(OUT, 'SUMMARY.md'), 'w', encoding='utf-8') as fh:
        fh.write('\n'.join(lines))
    print(dict(dec))


if __name__ == '__main__':
    main()
